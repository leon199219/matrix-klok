static inline const Glyph* findGlyph(char c) {
  if (c >= 'a' && c <= 'z') c -= 32;
  for (const Glyph& g : FONT3x5) if (g.c == c) return &g;
  return &FONT3x5[sizeof(FONT3x5)/sizeof(FONT3x5[0]) - 4]; // '?'
}
